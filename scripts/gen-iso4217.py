#!/usr/bin/env python3
"""Generate src/Cal/Currency/Table.hs from the SIX ISO 4217 list one."""
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

URL = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml"
OUT = Path(__file__).resolve().parent.parent / "src/Cal/Currency/Table.hs"

with urllib.request.urlopen(URL, timeout=60) as r:
    root = ET.fromstring(r.read())

published = root.get("Pblshd", "unknown")
minor = {
    e.findtext("Ccy"): int(e.findtext("CcyMnrUnts"))
    for e in root.iter("CcyNtry")
    if e.findtext("Ccy") and e.findtext("CcyMnrUnts") != "N.A."
}
codes = sorted(minor)

lines = [
    f"-- Generated by scripts/gen-iso4217.py. Do not edit.",
    f"-- Source: {URL}",
    f"-- List published: {published}",
    "module Cal.Currency.Table (iso4217, iso4217MinorUnits) where",
    "",
    "import Data.Map.Strict (Map)",
    "import qualified Data.Map.Strict as Map",
    "import Data.Set (Set)",
    "import qualified Data.Set as Set",
    "import Data.Text (Text)",
    "",
    "iso4217 :: Set Text",
    "iso4217 =",
    "  Set.fromList",
]
for i, c in enumerate(codes):
    lines.append(f"    {'[' if i == 0 else ','} \"{c}\"")
lines.append("    ]")
lines += [
    "",
    "-- | Each code's minor units (decimal places), as the list gives them.",
    "iso4217MinorUnits :: Map Text Int",
    "iso4217MinorUnits =",
    "  Map.fromList",
]
for i, c in enumerate(codes):
    lines.append(f"    {'[' if i == 0 else ','} (\"{c}\", {minor[c]})")
lines.append("    ]")
OUT.write_text("\n".join(lines) + "\n")
